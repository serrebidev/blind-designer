//! font: a built-in 5 by 7 bitmap font, so text elements render with
//! no font files and no extra dependencies.
//!
//! Each glyph is 7 rows of 5 pixels, one byte per row, bit 4 the
//! leftmost pixel. It covers the printable ASCII a short caption or
//! label needs: letters, digits and common punctuation. Anything else
//! returns `None` and the renderer falls back to '?'.
//! ponytail: hand-drawn glyphs by design — upgrade path is a real font
//! crate (ab_glyph + a bundled TTF) if text elements ever need
//! proportional type or scripts beyond Latin.

