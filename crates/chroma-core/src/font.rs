#[cfg(test)]
mod tests {
	use super::*;

	#[test]
	fn known_glyphs_have_their_classic_shapes() {
		// 'A': pointed top, crossbar in the middle row.
		let a = glyph('A').unwrap();
		assert_eq!(a[0], 0b01110);
		assert_eq!(a[3], 0b11111);
		// 'I' is a narrow stem with serifs; 'O' is a closed ring.
		assert_eq!(glyph('I').unwrap()[0], 0b01110);
		assert_eq!(glyph('O').unwrap()[1], 0b10001);
		assert_eq!(glyph('0').unwrap()[3], 0b10101); // slashed-zero middle
		assert_eq!(glyph(' ').unwrap(), [0; 7]);
	}

	#[test]
	fn every_printable_ascii_char_draws_something_except_space() {
		for code in 33u8..127 {
			let c = code as char;
			let g = glyph(c).unwrap_or_else(|| panic!("no glyph for {c}"));
			assert!(g.iter().any(|&row| row != 0), "glyph for {c} is blank");
		}
		assert!(glyph('é').is_none());
		assert!(glyph('\n').is_none());
	}

	#[test]
	fn distinct_letters_have_distinct_glyphs() {
		assert_ne!(glyph('A'), glyph('B'));
		assert_ne!(glyph('O'), glyph('0'));
		assert_ne!(glyph('a'), glyph('A'));
	}
}
